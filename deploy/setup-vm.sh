#!/usr/bin/env bash
# One-shot setup of MAW on a fresh Ubuntu 22.04/24.04 VM (Hetzner, Oracle, DigitalOcean, ...).
#
#   curl -fsSL https://raw.githubusercontent.com/dinup07/maw-api/<branch>/deploy/setup-vm.sh -o setup-vm.sh
#   sudo BRANCH=<branch> bash setup-vm.sh
#
# Installs Docker, opens only SSH/HTTP/HTTPS, clones the repo to /opt/maw, writes /opt/maw/.env with
# generated secrets (first run only), starts the stack behind Caddy with a free <ip>.sslip.io
# HTTPS hostname, and installs a nightly database backup. Safe to re-run.
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/dinup07/maw-api.git}"
BRANCH="${BRANCH:-main}"
APP_DIR="${APP_DIR:-/opt/maw}"
COMPOSE=(docker compose -f docker-compose.yml -f deploy/docker-compose.prod.yml)

log() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo)"; exit 1; }

log "Installing packages (Docker, git, ufw)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q git curl ufw ca-certificates openssl
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker

log "Firewall: allow SSH, HTTP, HTTPS only"
ufw allow OpenSSH >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw --force enable >/dev/null
# Note: Docker-published ports bypass ufw; the production overlay publishes only Caddy's 80/443.

log "Fetching the code ($REPO_URL, branch $BRANCH) into $APP_DIR"
if [ -d "$APP_DIR/.git" ]; then
  git -C "$APP_DIR" fetch -q origin "$BRANCH"
  git -C "$APP_DIR" checkout -q "$BRANCH"
  git -C "$APP_DIR" reset -q --hard "origin/$BRANCH"
else
  git clone -q --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
fi
cd "$APP_DIR"

if [ ! -f .env ]; then
  log "Writing $APP_DIR/.env with generated secrets"
  PUBLIC_IP="${PUBLIC_IP:-$(curl -fsS -4 https://api.ipify.org || curl -fsS -4 https://ifconfig.me)}"
  HOSTNAME_SSLIP="${MAW_HOSTNAME:-${PUBLIC_IP//./-}.sslip.io}"
  API_KEY="$(openssl rand -hex 24)"
  cat > .env <<ENV
# Generated by deploy/setup-vm.sh on $(date -u +%F). Keep this file private (chmod 600).
MAW_HOSTNAME=${HOSTNAME_SSLIP}
POSTGRES_PASSWORD=$(openssl rand -hex 24)
MAW_API_KEYS=["${API_KEY}"]
# Hosts MAW may call. Add any MCP servers, A2A agents or vector databases you configure.
MAW_ALLOWED_OUTBOUND_HOSTS=["api.openai.com","generativelanguage.googleapis.com","mock-mcp","mock-a2a","qdrant","${HOSTNAME_SSLIP}"]
MAW_ALLOW_WORKFLOW_REGISTRATION=true
# Provider keys (uncomment and set, then: sudo bash deploy/update.sh)
# OPENAI_API_KEY=sk-...
# GOOGLE_API_KEY=AIza...
ENV
  chmod 600 .env
fi
MAW_HOSTNAME="$(sed -n 's/^MAW_HOSTNAME=//p' .env)"  # read just what we need; .env holds JSON values

log "Building and starting the stack (first build takes a few minutes)"
"${COMPOSE[@]}" up -d --build

log "Installing the nightly backup (02:30, keeps 14 days)"
install -m 755 deploy/backup.sh /usr/local/bin/maw-backup
cat > /etc/cron.d/maw-backup <<CRON
30 2 * * * root APP_DIR=${APP_DIR} /usr/local/bin/maw-backup >> /var/log/maw-backup.log 2>&1
CRON

log "Waiting for MAW to become ready"
for _ in $(seq 1 60); do
  if "${COMPOSE[@]}" exec -T maw python -c "import urllib.request,sys; sys.exit(0 if urllib.request.urlopen('http://127.0.0.1:8000/ready', timeout=2).status == 200 else 1)" 2>/dev/null; then
    READY=1; break
  fi
  sleep 3
done
[ "${READY:-0}" = 1 ] || { echo "MAW did not become ready; see: ${COMPOSE[*]} logs maw"; exit 1; }

API_KEY_SHOWN="$(sed -n 's/^MAW_API_KEYS=\["\(.*\)"\]$/\1/p' .env | cut -d'"' -f1)"
cat <<DONE

MAW is running.
  URL:      https://${MAW_HOSTNAME}        (the HTTPS certificate can take a minute on first start)
  API docs: https://${MAW_HOSTNAME}/docs
  API key:  ${API_KEY_SHOWN}     (also in ${APP_DIR}/.env)

Try:
  curl -s https://${MAW_HOSTNAME}/ready
  curl -s https://${MAW_HOSTNAME}/v1/runs -H "X-API-Key: ${API_KEY_SHOWN}" -H 'content-type: application/json' \\
    -d '{"workflow_id": "support_triage", "input": "Was INV-1001 charged twice?"}'

Next: add provider keys to ${APP_DIR}/.env, then run: sudo bash ${APP_DIR}/deploy/update.sh
DONE
